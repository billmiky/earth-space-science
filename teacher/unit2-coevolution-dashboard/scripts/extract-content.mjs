// extract-content.mjs — Regenerate src/content/quizzes.js and src/content/myths.js from the
// student chapter, so the dashboard's checks use the chapter's exact wording.
//
//   node scripts/extract-content.mjs
//
// It reads unit2-probability-of-life/unit2-coevolution.qmd, finds every buildQuiz(...) /
// buildCoevoQuiz(...) call and the Myth-or-Fact `var cards = [...]` array, and evaluates each
// array literal on its own (the chapter's table helper is replaced with a dashboard-styled one).

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const qmdRel = "unit2-probability-of-life/unit2-coevolution.qmd";
const qmd = readFileSync(join(root, "..", "..", qmdRel), "utf8");

// Dashboard version of the chapter's coevoQTable helper (styled by styles.css, dark theme).
const coevoQTable = (head, rows) =>
  `<div class="table-host"><table class="data compact q-table"><thead><tr>${head.map((h) => `<th>${h}</th>`).join("")}</tr></thead>` +
  `<tbody>${rows.map((r) => `<tr>${r.map((c) => `<td>${c}</td>`).join("")}</tr>`).join("")}</tbody></table></div>`;

/** Evaluate the array literal that starts at `start` (an index of "["). Tries each "]" in turn. */
function evalArrayAt(src, start) {
  for (let end = src.indexOf("]", start); end !== -1; end = src.indexOf("]", end + 1)) {
    const lit = src.slice(start, end + 1);
    try {
      // eslint-disable-next-line no-new-func
      const v = new Function("coevoQTable", `"use strict"; return (${lit});`)(coevoQTable);
      if (Array.isArray(v)) return v;
    } catch { /* not the closing bracket yet */ }
  }
  throw new Error(`Could not parse array at ${start}`);
}

const QUIZZES = {};
const re = /build(?:Coevo)?Quiz\("([\w-]+)",\s*"([^"]+)",\s*\[/g;
for (const m of qmd.matchAll(re)) {
  const questions = evalArrayAt(qmd, m.index + m[0].length - 1).map((q) => ({
    q: q.q.trim().replace(/\s*\n\s*/g, " "), options: q.options, correct: q.correct, explanation: q.explanation,
  }));
  QUIZZES[m[1]] = { title: m[2], questions };
}

const cardsAt = qmd.indexOf("var cards = [");
if (cardsAt < 0) throw new Error("Myth or Fact cards not found");
const MYTHS = evalArrayAt(qmd, cardsAt + "var cards = ".length);

const banner = `// Generated by scripts/extract-content.mjs from ${qmdRel}. Do not edit by hand;\n// change the chapter and re-run the script so the dashboard and chapter stay in sync.\n\n`;
writeFileSync(join(root, "src/content/quizzes.js"), `${banner}export const QUIZZES = ${JSON.stringify(QUIZZES, null, 2)};\n`);
writeFileSync(join(root, "src/content/myths.js"), `${banner}export const MYTHS = ${JSON.stringify(MYTHS, null, 2)};\n`);
console.log(`quizzes: ${Object.entries(QUIZZES).map(([k, v]) => `${k}(${v.questions.length})`).join(", ")}`);
console.log(`myths: ${MYTHS.length}`);
